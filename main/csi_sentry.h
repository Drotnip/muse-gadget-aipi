#pragma once

/*
 * Wi-Fi CSI motion sentry (CONFIG_MUSE_CSI_SENTRY).
 *
 * Watches the channel state information of the gadget's own Wi-Fi link for
 * the ripples a moving body makes: jitter (frame-to-frame change) reads as
 * motion, wander (deviation from the learned empty-room baseline) reads as
 * presence. The detection engine is a port of the standalone CSI motion
 * sense project (jitter/wander metrics, 20 s calibration, thresholds in
 * NVS). Traffic is generated by pinging the gateway at 20 Hz.
 *
 * Sustained motion raises an alert: a message posted into the Muse chat
 * through the typed-turn API (CONFIG_MUSE_HATCH) and a caption on the
 * screen. Everything runs in one low-priority task; a failure here never
 * takes the gadget down.
 *
 * Recalibration is requested through the settings (the menu's
 * "Recalibrate sentry" row, the BLE "sentry_cal" command): the stored
 * thresholds are erased and a fresh 20 s learn runs, announced with the
 * CALIBRATING caption and confirmed with "SENTRY READY". If CSI frames
 * stop flowing while the sentry is on, a "SENTRY: NO SIGNAL" caption
 * says so instead of silently standing guard over nothing. Requires
 * CONFIG_ESP_WIFI_CSI_ENABLED: without it the Wi-Fi driver has no CSI
 * support compiled in and no frame ever reaches the callback.
 */

// Starts the sentry task. Call once from app_main; the task waits for
// Wi-Fi before it touches the radio, CSI or NVS.
void csi_sentry_start(void);
